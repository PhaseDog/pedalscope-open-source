def main(argv=None):
    p = argparse.ArgumentParser()
    p.add_argument("--no-parity", action="store_true", help="skip the parity table (no Swift tool needed)")
    args = p.parse_args(argv)
    os.makedirs(GENERATED, exist_ok=True)
    m = hd.load_manifest()
    with open(hd.DEFAULT_MANIFEST, encoding="utf-8") as f:
        whole = json.load(f)
    transfer = whole["transferCurve"]
    gen_terms(load_terms())
    gen_parameters(m)
    gen_windows(m)
    gen_parameters_transfer(transfer)
    gen_parameters_imd(whole["chordIMD"])
    gen_lattice_imd(whole["chordIMD"])
    gen_parameters_journey(whole["gainMap"])
    gen_residue_journey(whole["gainMap"])
