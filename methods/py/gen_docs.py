def _parity_scalar(parity_file: str, name: str) -> str:
    """The literal a single-line scalar macro prints in a parity fragment
    (the plain writer names a note beside a frequency the parity run chose;
    the value itself stays the fragment's)."""
    with open(parity_file, encoding="utf-8") as f:
        for line in f:
            m = SCALAR_MACRO.match(line)
            if m and m.group(1) == name:
                return m.group(2)
    raise AssertionError(f"{parity_file} defines no scalar {name}")


def _parity_table_rows(parity_file: str, name: str):
    """The data rows of a tabular macro in a parity fragment — the lines
    between its \\toprule and \\bottomrule that end a row."""
    rows, inside = [], False
    with open(parity_file, encoding="utf-8") as f:
        for line in f:
            if line.startswith(r"\newcommand{\%s}" % name):
                inside = True
                continue
            if inside and line.startswith(r"\bottomrule"):
                break
            if inside and line.rstrip().endswith(r"\\") and not line.startswith(r"\toprule"):
                rows.append([c.strip() for c in line.rstrip()[:-2].split("&")])
    assert rows, f"{parity_file} carries no table {name}"
    return rows


