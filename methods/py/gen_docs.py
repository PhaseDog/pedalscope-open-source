# --- Numbers in words (#307) --------------------------------------------------
# A tolerance such as 1e-10 prints as "1e-10" in lay prose because the parity
# macros are shared with the technical chapter. Beside each scalar macro the
# lay chapter quotes, a WORDS form is generated from the same value: an exact
# power of ten is named ("a ten-billionth"), anything else is stated as
# "about N × 10^k" in words ("about seven ten-trillionths"). A value the
# formatter cannot name comes back as the number itself — never a guess.

FRACTION_NAMES = {
    1: "tenth", 2: "hundredth", 3: "thousandth", 4: "ten-thousandth",
    5: "hundred-thousandth", 6: "millionth", 7: "ten-millionth",
    8: "hundred-millionth", 9: "billionth", 10: "ten-billionth",
    11: "hundred-billionth", 12: "trillionth", 13: "ten-trillionth",
    14: "hundred-trillionth", 15: "quadrillionth",
}
ONES = {1: "one", 2: "two", 3: "three", 4: "four", 5: "five", 6: "six", 7: "seven", 8: "eight", 9: "nine"}
# The three fractions English names outright; every other value goes through
# the power-of-ten rule.
NAMED_FRACTIONS = {0.5: "a half", 0.25: "a quarter", 0.75: "three quarters"}


def in_words(value, fallback: str) -> str:
    """The English name of a positive value under one, or `fallback` (the
    number as the number macro prints it) when there is no name for it."""
    try:
        v = float(value)
    except (TypeError, ValueError):
        return fallback
    if not math.isfinite(v) or not (0 < v < 1):
        return fallback
    for named, name in NAMED_FRACTIONS.items():
        if abs(v - named) <= 1e-12:
            return name
    k = -math.floor(math.log10(v))          # 10^-k <= v < 10^-(k-1)
    mantissa = round(v * 10 ** k, 1)        # two significant figures
    if mantissa >= 10:
        k -= 1
        mantissa = 1.0
    if k not in FRACTION_NAMES:
        return fallback
    name = FRACTION_NAMES[k]
    if mantissa == 1.0:
        return f"a {name}"
    if mantissa == int(mantissa):
        return f"{ONES[int(mantissa)]} {name}s"
    rounded = int(math.floor(mantissa + 0.5))   # half up, never banker's
    if rounded >= 10:
        k -= 1
        if k not in FRACTION_NAMES:
            return fallback
        return f"about a {FRACTION_NAMES[k]}"
    if rounded == 1:
        return f"about a {name}"
    return f"about {ONES[rounded]} {name}s"


SCALAR_MACRO = re.compile(r"^\\newcommand\{\\([A-Za-z]+)\}\{(-?[0-9.]+(?:e-?[0-9]+)?)\}\s*$")
# A measured deviation under the machine floor (`dev`): the bound form.
BOUND_MACRO = re.compile(r"^\\newcommand\{\\([A-Za-z]+)\}\{\$\\le\$\\,([0-9.]+(?:e-?[0-9]+)?)\}\s*$")


def parity_words_macros(parity_file: str):
    """One `\\<name>Words` macro per single-line scalar `\\newcommand` in a
    committed (or just regenerated) parity fragment, derived from the literal
    the fragment prints so that the number and its words cannot disagree.
    Tables and sentences (multi-line or non-numeric) carry no words form."""
    out = []
    with open(parity_file, encoding="utf-8") as f:
        for line in f:
            m = SCALAR_MACRO.match(line)
            if m:
                name, literal = m.group(1), m.group(2)
                out.append(r"\newcommand{\%sWords}{%s}" % (name, in_words(literal, literal)) + "\n")
                continue
            m = BOUND_MACRO.match(line)
            if m:
                # A bound reads "under <the floor in words>" — the floor is
                # an exact power of ten, so it always has a name.
                name, literal = m.group(1), m.group(2)
                out.append(r"\newcommand{\%sWords}{under %s}" % (name, in_words(literal, literal)) + "\n")
    return out


