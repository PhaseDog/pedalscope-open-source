NOTE_NAMES = ["C", "C\\#", "D", "D\\#", "E", "F", "F\\#", "G", "G\\#", "A", "A\\#", "B"]


def nearest_note(hz: float) -> str:
    """The nearest equal-tempered note name, A4 = 440 Hz (the convention the
    guide's tuning page states) — a naming aid beside a frequency, never a
    measured quantity."""
    semitones = int(round(12 * math.log2(hz / 440.0)))
    index = (semitones + 9) % 12          # 0 = C
    octave = 4 + (semitones + 9) // 12
    return f"{NOTE_NAMES[index]}{octave}"


