def tex_escape(s: str) -> str:
    return (s.replace("\\", r"\textbackslash{}").replace("&", r"\&").replace("%", r"\%")
             .replace("$", r"\$").replace("#", r"\#").replace("_", r"\_").replace("{", r"\{")
             .replace("}", r"\}").replace("~", r"\textasciitilde{}").replace("^", r"\textasciicircum{}"))


def num(v, sig=6) -> str:
    if isinstance(v, bool):
        return "yes" if v else "no"
    if isinstance(v, int):
        return f"{v:,}".replace(",", r"\,")
    if v is None:
        return "--"
    if isinstance(v, float):
        if math.isinf(v):
            return r"$-\infty$" if v < 0 else r"$\infty$"
        if v == int(v) and abs(v) < 1e15:
            return f"{int(v):,}".replace(",", r"\,")
        return f"{v:.{sig}g}"
    return tex_escape(str(v))


def dev(v, sig=6) -> str:
    """A MEASURED deviation — a Swift−Python difference, an error against
    truth, a residue, a shift, a move: the ONE formatter for every such
    figure in every parity fragment (ruled 2026-09-22, `machine_floor.py`).
    Under the machine floor it prints the bound; at or above it, `num`'s
    digits. A stated bar never comes through here — it goes through `num`."""
    return mf.bound_text() if mf.under_floor(v) else num(v, sig)


def gen_machine_floor(out_dir: str = GENERATED) -> str:
    """The fragment that quotes the floor the documents were built under,
    so a chapter prints the floor it used rather than a typed number."""
    text = ("% GENERATED by gen_docs.py from machine_floor.py — do not edit\n"
            + r"\newcommand{\machineFloor}{%s}" % mf.floor_text() + "\n"
            + r"\newcommand{\machineFloorWords}{%s}" % in_words(mf.MACHINE_FLOOR, mf.floor_text()) + "\n"
            + r"\newcommand{\sidecarFigures}{%d}" % mf.SIDECAR_SIGNIFICANT_FIGURES + "\n")
    path = os.path.join(out_dir, "machine-floor.tex")
    write(path, text)
    return path


def load_terms():
    with open(TERMS, encoding="utf-8") as f:
        data = yaml.safe_load(f)
    terms = data["terms"]
    keys = [t["key"] for t in terms]
    assert len(keys) == len(set(keys)), "duplicate term keys"
    for t in terms:
        for field in ("key", "term", "technical", "plain"):
            assert t.get(field), f"term {t.get('key')!r} lacks {field}"
        assert re.fullmatch(r"[a-z][a-z0-9-]*", t["key"]), f"bad key {t['key']!r}"
    return terms


def write(path, text):
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def gen_terms(terms):
    macros = ["% GENERATED by gen_docs.py from terms.yaml — do not edit\n"]
    for t in terms:
        macros.append(r"\expandafter\newcommand\csname term@%s\endcsname{%s}" % (t["key"], t["term"]) + "\n")
    write(os.path.join(GENERATED, "terms-macros.tex"), "".join(macros))

    def entry(t, plain):
        sym = f" ({t['symbol']})" if t.get("symbol") else ""
        body = t["plain"] if plain else t["technical"]
        return (r"\item[{\hypertarget{term:%s}{%s}%s}] %s"
                % (t["key"], t["term"], sym, body) + "\n")

    ordered = sorted(terms, key=lambda t: t["term"].lower())
    for name, plain in (("glossary.tex", False), ("glossary-plain.tex", True)):
        out = ["% GENERATED by gen_docs.py from terms.yaml — do not edit\n",
               r"\begin{description}" + "\n"]
        out += [entry(t, plain) for t in ordered]
        out.append(r"\end{description}" + "\n")
        write(os.path.join(GENERATED, name), "".join(out))


