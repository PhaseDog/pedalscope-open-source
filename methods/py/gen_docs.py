def bar_lines(bars):
    return [r"\newcommand{\%s}{%s}" % (macro, num(value, 3)) + "\n" for macro, value in bars]


def gen_parity(m):
    import parity_hd as P
    tool = P.build_tool()
    out = ["% GENERATED by gen_docs.py from a parity run (Swift vs Python vs analytic) — do not edit\n"]
    out.extend(bar_lines(bars_hd()))
    out.append(r"\newcommand{\parityPerSampleTolerances}{%s}" % ", ".join(
        f"{tex_escape(k)} {num(v, 3)} dB" for k, v in P.T_ANALYTIC_PER_SAMPLE.items()) + "\n")
    cases = list(P.CASES)
    reports = {}
    twins = {}
    for case in cases:
        swift = P.run_swift(tool, case)
        reports[case.name] = P.compare(case, swift, P.run_python(case), m)
        if case.source != "phantom":
            twin = P.phantom_twin(case, swift)
            twins[case.name] = P.compare(twin, P.run_swift(tool, twin), P.run_python(twin), m)
    noisy = P.compare(P.NOISY, P.run_swift(tool, P.NOISY), P.run_python(P.NOISY), m)

    out.append(r"\newcommand{\parityTable}{" + "\n")
    out.append(r"\begin{longtable}{@{}p{0.2\linewidth}rrrrrr@{}}" + "\n")
    out.append(r"\toprule case & $k$ & expected & S$-$P & S$-$T band & P$-$T band & S$-$T full \\" + "\n")
    out.append(r" & & (dB) & (dB) & (dB) & (dB) & (dB) \\ \midrule \endhead" + "\n")
    for case in cases:
        r = reports[case.name]
        for o in r.content_orders():
            out.append(f"{tex_escape(case.name)} & {o.order} & {num(o.expected_db, 5)} & {dev(o.max_swift_vs_python, 2)} & {dev(o.max_swift_vs_analytic_band, 3)} & {dev(o.max_python_vs_analytic_band, 3)} & {dev(o.max_swift_vs_analytic_full, 3)} \\\\\n")
        if case.name in twins:
            for o in twins[case.name].content_orders():
                out.append(f"{tex_escape(case.name)} twin & {o.order} & {num(o.expected_db, 5)} & {dev(o.max_swift_vs_python, 2)} & {dev(o.max_swift_vs_analytic_band, 3)} & {dev(o.max_python_vs_analytic_band, 3)} & {dev(o.max_swift_vs_analytic_full, 3)} \\\\\n")
    out.append(r"\bottomrule" + "\n" + r"\end{longtable}" + "\n}\n")

    out.append(r"\newcommand{\parityNoisyTable}{" + "\n")
    out.append(r"\begin{tabular}{@{}rrrrrr@{}}" + "\n")
    out.append(r"\toprule $k$ & expected (dB) & shaped points & S$-$P (dB) & S$-$T shaped, band (dB) & error / allowance \\ \midrule" + "\n")
    for o in noisy.content_orders():
        out.append(f"{o.order} & {num(o.expected_db, 5)} & {o.shaped_both} & {dev(o.max_swift_vs_python, 2)} & {dev(o.max_swift_vs_analytic_band, 3)} & {dev(o.max_scatter_normalized, 2)} \\\\\n")
    out.append(r"\bottomrule" + "\n" + r"\end{tabular}" + "\n}\n")

    tanh = reports["tanh"]
    o1 = next(o for o in tanh.content_orders() if o.order == 1)
    o3 = next(o for o in tanh.content_orders() if o.order == 3)
    o9 = next(o for o in tanh.content_orders() if o.order == 9)
    out.append(r"\newcommand{\parityTanhHone}{%s}" % num(o1.expected_db, 5) + "\n")
    out.append(r"\newcommand{\parityTanhHthree}{%s}" % num(o3.expected_db, 5) + "\n")
    out.append(r"\newcommand{\parityTanhHnine}{%s}" % num(o9.expected_db, 5) + "\n")
    out.append(r"\newcommand{\parityTanhFullBand}{%s}" % dev(P.full_band_max(tanh), 3) + "\n")
    out.append(r"\newcommand{\parityHardclipFullBand}{%s}" % dev(P.full_band_max(reports["hardclip"]), 3) + "\n")
    out.append(r"\newcommand{\parityWorstSwift}{%s}" % dev(max(o.max_swift_vs_python for r in reports.values() for o in r.content_orders()), 2) + "\n")
    write(os.path.join(GENERATED, "parity-hd.tex"), "".join(out))


