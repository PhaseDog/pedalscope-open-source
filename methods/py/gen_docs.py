def _join_words(items):
    items = list(items)
    if len(items) <= 1:
        return "".join(items)
    return ", ".join(items[:-1]) + " and " + items[-1]


def _khz(rate) -> str:
    """A sample rate in kHz as the guide writes it: 96, 48, 88.2, 44.1."""
    k = rate / 1000.0
    return num(int(k)) if k == int(k) else num(k, 4)


def _enumerate_bins(k1: int, k2: int, bw: float, fs: float, max_order: int):
    """The analyzer's walk (`analyzer.enumerationRule`) on integer bins:
    (m, n, order, bin) for every admitted recipe, the lowest order keeping
    a shared bin."""
    seen = {k1, k2, 0}
    out = []
    limit_bins = 0.95 * fs / 2 / bw
    for order in range(2, max_order + 1):
        for mm in range(-order, order + 1):
            nm = order - abs(mm)
            for nn in (nm, -nm):
                if abs(mm) + abs(nn) != order:
                    continue
                b = mm * k1 + nn * k2
                if not (1 <= b < limit_bins):
                    continue
                if b in seen:
                    continue
                seen.add(b)
                out.append((mm, nn, order, b))
    return out


def _recipe_label(mm: int, nn: int) -> str:
    def part(c, name):
        if c == 0:
            return ""
        mag = "" if abs(c) == 1 else str(abs(c))
        return ("-" if c < 0 else "+") + mag + name
    s = part(mm, "f1") + part(nn, "f2")
    return s.lstrip("+").replace("+", "+").replace("-", "\u2212")


